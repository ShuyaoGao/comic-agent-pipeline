# -*- coding: utf-8 -*-
"""One command to build the static page (play/) and the release zip.

    python -m tools.build              # play/js/credits.js + play/js/sample_export.js
    python -m tools.build --release    # also write release/<repo>-v<version>.zip (play/ + root index.html)

play/ is plain HTML + JS: it runs from file:// (double-click play/index.html) without Python.
Nothing is compiled; this script only writes two generated data files and zips play/.
"""

import argparse
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAY = ROOT / "play"
RELEASE = ROOT / "release"
ZIP_LIMIT = 15 * 1024 * 1024


def load_credits():
    return json.loads((ROOT / "credits.json").read_text(encoding="utf-8"))


def write_js(name, var, payload, note):
    out = PLAY / "js" / name
    out.write_text(f"/* Generated by tools/build.py from {note} -- edit that file, then rebuild. */\n"
                   f"window.{var} = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n",
                   encoding="utf-8", newline="\n")
    return out


def root_index(credits):
    """The repository-root index.html (meta refresh to play/index.html) that also goes into the zip, so that
    "unzip, then double-click index.html" works. Taken from the rendered file if present, else from the template."""
    for p in (ROOT / "index.html", ROOT / "tools" / "templates" / "index.html", ROOT / "tools" / "publish_templates" / "index.html"):
        if p.exists():
            s = p.read_text(encoding="utf-8")
            return re.sub(r"\{\{([A-Z0-9_]+)\}\}", lambda m: str(credits.get(m.group(1), m.group(0))), s).encode("utf-8")
    return None


def make_zip(credits):
    """release/<repo>-v<version>.zip = play/ + the root index.html (nothing else)."""
    RELEASE.mkdir(exist_ok=True)
    name = f"{credits.get('REPO_NAME', 'comic-agent-pipeline')}-v{credits.get('VERSION', '1.0')}.zip"
    out = RELEASE / name
    files = sorted(p for p in PLAY.rglob("*") if p.is_file())
    entries = [("play/" + p.relative_to(PLAY).as_posix(), p.read_bytes()) for p in files]
    idx = root_index(credits)
    if idx is not None:
        entries.insert(0, ("index.html", idx))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for arc, data in entries:
            info = zipfile.ZipInfo(arc, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    size = out.stat().st_size
    if size > ZIP_LIMIT:
        raise SystemExit(f"release zip is {size} bytes > 15 MB limit")
    return out, size, len(entries)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--release", action="store_true", help="also build the release zip")
    args = ap.parse_args(argv)
    credits = load_credits()
    keep = {k: v for k, v in credits.items() if not k.startswith("_")}
    print("wrote", write_js("credits.js", "CREDITS", keep, "credits.json").relative_to(ROOT).as_posix())
    sample = json.loads((ROOT / "tools" / "sample_director_export.json").read_text(encoding="utf-8"))
    print("wrote", write_js("sample_export.js", "SAMPLE_DIRECTOR_EXPORT", sample,
                            "tools/sample_director_export.json").relative_to(ROOT).as_posix())
    total = sum(p.stat().st_size for p in PLAY.rglob("*") if p.is_file())
    print(f"play/ = {total} bytes")
    if args.release:
        out, size, n = make_zip(credits)
        print(f"wrote {out.relative_to(ROOT).as_posix()}: {n} files, {size} bytes")


if __name__ == "__main__":
    main()
